// Generates public-next/split-cq.css: the human column is a size container ("hcol"), so the page's
// responsive rules must answer to the COLUMN width, not the viewport. This mirrors every
// @media (max/min-width) block of styles.css + glass.css as @container hcol, and every vw-based
// declaration as cqi, scoped to .col-human. Run: node scripts/gen-split-cq.mjs [publicDir]
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
const dir = process.argv[2] || path.resolve(path.dirname(new URL(import.meta.url).pathname), '../public-next');
const src = ['styles.css', 'glass.css'].map(f => readFileSync(path.join(dir, f), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')).join('\n');

function parse(css) { // -> [{sel, body}] | [{at, rules}]
  const out = []; let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i); if (open < 0) break;
    const head = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    if (head.startsWith('@')) out.push({ at: head, rules: /^@(media|supports)/.test(head) ? parse(body) : [] });
    else if (head) out.push({ sel: head, body });
    i = j;
  }
  return out;
}
const scope = sel => sel.split(',').map(s => {
  s = s.trim();
  if (s === ':root' || s === 'html' || s === 'body') return '.col-human';
  const m = s.match(/^(html(?:\[[^\]]+\]|:not\([^)]*\)|\.[\w-]+)*)\s+(.*)$/);
  return m ? `${m[1]} .col-human ${m[2]}` : `.col-human ${s}`;
}).join(', ');
const cq = v => v.replace(/(\d)vw\b/g, '$1cqi');
const decls = body => body.split(';').map(d => d.trim()).filter(Boolean);
let out = '/* GENERATED by scripts/gen-split-cq.mjs — do not edit. Column-aware copies of the responsive rules. */\n';
for (const r of parse(src)) {
  if (r.sel) { const vw = decls(r.body).filter(d => /\dvw\b/.test(d)); if (vw.length) out += `${scope(r.sel)} { ${vw.map(cq).join('; ')}; }\n`; }
  else if (/^@media\b/.test(r.at) && /(max|min)-width/.test(r.at) && !/prefers|print|hover|pointer/.test(r.at)) {
    const cond = r.at.replace(/^@media\s*/, '').replace(/\bscreen and\s*/g, '');
    const inner = r.rules.filter(x => x.sel).map(x => `  ${scope(x.sel)} { ${cq(x.body.trim())} }`).join('\n');
    if (inner) out += `@container hcol ${cond} {\n${inner}\n}\n`;
  }
}
const target = path.join(dir, 'split.css'); const base = readFileSync(target, 'utf8').split('/* GENERATED by scripts/gen-split-cq.mjs')[0]; writeFileSync(target, base + out);
console.log('appended', out.length, 'bytes of container rules to', target);
